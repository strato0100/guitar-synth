def instrument_list():
    instruments = []
    for c, (category, icon, names) in enumerate(CATEGORIES):
        for i, pair in enumerate(names):
            es, en = pair.split("|")
            instruments.append({"program": c * 8 + i, "name": es, "en": en,
                                "category": category, "icon": icon})
    return instruments


def category_list():
    return [{"name": name, "icon": icon} for name, icon, _ in CATEGORIES]
